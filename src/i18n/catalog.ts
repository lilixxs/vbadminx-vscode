const catalogs: Record<Locale, Record<MessageKey, string>> = {
  en,
  'zh-cn': zhCn,
  'zh-tw': zhTw,
  ja,
  ko,
};

/** 把 VS Code 的 language 标签归一化到支持的语言；未匹配时返回 en。 */
export function normalizeLanguageTag(tag: string | undefined): Locale {
  const value = (tag ?? '').trim().toLowerCase().replaceAll('_', '-');
  if (!value) { return 'en'; }
  if (value.startsWith('zh')) {
    // zh-tw / zh-hk / zh-mo / zh-hant 使用繁体；其余中文（含 zh、zh-cn、zh-hans）使用简体。
    return /(^|-)tw($|-)|(^|-)hk($|-)|(^|-)mo($|-)|hant/.test(value) ? 'zh-tw' : 'zh-cn';
  }
  if (value.startsWith('ja')) { return 'ja'; }
  if (value.startsWith('ko')) { return 'ko'; }
  if (value.startsWith('en')) { return 'en'; }
  return 'en';
}

export function formatMessage(template: string, args: ReadonlyArray<string | number>): string {
  let text = template;
  for (let index = 0; index < args.length; index += 1) {
    text = text.replaceAll(`{${index}}`, String(args[index]));
  }
  return text;
}

/** 取指定语言的文案；缺失时回退英文，再回退键名。 */
export function translate(locale: Locale, key: MessageKey, ...args: Array<string | number>): string {
  const template = catalogs[locale]?.[key] ?? catalogs.en[key] ?? key;
  return formatMessage(template, args);
}

export function catalogFor(locale: Locale): Record<MessageKey, string> {
  return catalogs[locale];
}

